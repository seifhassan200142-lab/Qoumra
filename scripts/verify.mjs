import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const ctx=vm.createContext({window:{},URL,Date});
for(const file of ['config','content','render'])vm.runInContext(fs.readFileSync(path.join(root,'js',file+'.js'),'utf8'),ctx);
for(const locale of ['en','ar']) {
 const html=ctx.window.QoumraRender(locale);
 const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
 assert.equal(ids.length,new Set(ids).size,'IDs must be unique');
 for(const id of ['home','services','portfolio','packages','about','contact'])assert(ids.includes(id));
 for(const m of html.matchAll(/href="#([^"]+)"/g))assert(ids.includes(m[1]),'Missing anchor '+m[1]);
 for(const m of html.matchAll(/(?:src|poster|href)="(assets\/[^"]+)"/g))assert(fs.existsSync(path.join(root,m[1])), 'Missing asset '+m[1]);
 assert.equal((html.match(/class="photo-slot"/g)||[]).length,12);
 assert.equal((html.match(/class="gallery-card"/g)||[]).length,3);
 assert(!html.includes('Interactive review'));
 assert(!/Q \/ 01|art-kicker|art-caption|لنخطط لنموك|حوّل الانتباه/.test(html));
 assert.equal((html.match(/<video /g)||[]).length,4);
 assert.equal((html.match(/controls autoplay muted loop playsinline/g)||[]).length,4);
 assert.equal((html.match(/data-find-service=/g)||[]).length,4);
 for(const id of ['ai','creative','web','growth']) assert(html.includes('aria-controls="film-'+id+'"'));
 assert(html.includes('type="submit" disabled'),'An unconfigured email must not claim submission');
}
ctx.window.QOUMRA_CONFIG.contact.email='hello@example.com';
ctx.window.QOUMRA_CONFIG.contact.phone='+201000000000';
ctx.window.QOUMRA_CONFIG.contact.facebook='https://www.facebook.com/example';
ctx.window.QOUMRA_CONFIG.contact.instagram='javascript:alert(1)';
let html=ctx.window.QoumraRender('en');
assert(html.includes('href="mailto:hello@example.com"'));
assert(html.includes('href="tel:+201000000000"'));
assert(html.includes('href="https://www.facebook.com/example"'));
assert(!html.includes('href="javascript:'));
assert(!html.includes('type="submit" disabled'));
ctx.window.QOUMRA_CONTENT.en.hero.line1='<script>alert(1)</script>';
assert(ctx.window.QoumraRender('en').includes('&lt;script&gt;alert(1)&lt;/script&gt;'));
console.log('Passed: 2 languages, 12 images, 6 sections, unique anchors, local assets, contact configuration, URL safety and text escaping.');
